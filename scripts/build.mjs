import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output = join(root,'dist');
const marker = join(output,'.bi-site-build');
const markerText = 'Generated by bi-across-clouds/scripts/build.mjs\n';

if (existsSync(output)) {
  if (!existsSync(marker) || await readFile(marker,'utf8') !== markerText) {
    throw new Error('Refusing to replace an unrecognized dist directory. Review/move it before building.');
  }
  await rm(output,{recursive:true});
}
await mkdir(output,{recursive:true});
for (const path of ['index.html','assets','src','data','examples','docs','README.md']) {
  await cp(join(root,path),join(output,path),{recursive:true});
}
await writeFile(marker,markerText);
console.log('Built dist: static HTML/CSS/JavaScript, catalogs, official assets, and reference starters.');
console.log('No cloud resources, tenant settings, source data, or credentials were deployed.');
